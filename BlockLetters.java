
public class BlockLetters{

public static void main(String[] args) {
    System.out.println(" A ");
    System.out.println("A A");
    System.out.println("AAA");
    System.out.println("A A");
    System.out.println("A A");
    System.out.println("\nEEE");
    System.out.println("E");
    System.out.println("E");
    System.out.println("E");
    System.out.println("EEE");

}

} 